const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1060}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.TF_TEST_URL || 'http://127.0.0.1:8000');
  await page.fill('#token', process.env.TF_TEST_TOKEN);
  await page.click('#connect');
  await page.waitForFunction(() => document.getElementById('tenant').textContent === 'acme');
  await page.setInputFiles('#file', path.resolve('examples/handbook.md'));
  await page.click('#upload-button');
  await page.waitForFunction(() => /Upload accepted|already exists/.test(document.getElementById('notice').textContent));
  await page.fill('#question', 'What is the annual leave policy?');
  await page.click('#ask-button');
  await page.waitForFunction(() => document.querySelector('.sources button'));
  if (!(await page.textContent('#chat')).includes('25')) throw new Error('Expected grounded answer missing');
  await page.click('.sources button');
  await page.waitForSelector('#source-dialog[open]');
  if (!(await page.textContent('#source-content')).includes('25')) throw new Error('Source evidence missing');
  await page.click('#close-dialog');
  fs.mkdirSync('artifacts', {recursive:true});
  await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (overflow) throw new Error('Desktop layout overflows');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Mobile layout overflows');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify({status:'passed',desktop:true,mobile:true,source_dialog:true,page_errors:errors}));
  await browser.close();
})().catch(e => {console.error(e);process.exit(1);});
